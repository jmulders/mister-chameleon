// ── tenant_domains ────────────────────────────────────────────────────────────

/**
 * Status of a custom domain registration.
 *
 *   pending — domain added; DNS / Vercel verification not yet confirmed.
 *   active  — domain is verified and fully operational.
 *   error   — domain verification failed or was rejected by Vercel.
 */
export type DomainStatus = "pending" | "active" | "error";

/**
 * One row per custom domain registered for a tenant.
 *
 * SQL migration: supabase/migrations/20240101000012_create_tenant_domains.sql
 */
export interface TenantDomainRow {
  /** UUID primary key. */
  id:                  string;
  /** Owning tenant slug, e.g. "workengine". */
  tenant_id:           string;
  /** Normalised hostname without protocol or trailing slash, e.g. "acme.com". */
  hostname:            string;
  /** True when this is the tenant's primary domain. */
  is_primary:          boolean;
  /** Verification and routing status. */
  status:              DomainStatus;
  /** Vercel domain ID returned by the Domains API, null when not using Vercel. */
  vercel_domain_id:    string | null;
  /** Vercel DNS verification records (CNAME / TXT) as returned by the API. */
  vercel_verification: Record<string, unknown> | null;
  /** Row creation timestamp. */
  created_at:          string;
  /** Last write timestamp. */
  updated_at:          string;
}

export interface TenantDomainInsert {
  /** Optional: omit to let the database generate a UUID. */
  id?:                  string;
  tenant_id:            string;
  hostname:             string;
  is_primary?:          boolean;
  /** Defaults to "pending" at the database level. */
  status?:              DomainStatus;
  vercel_domain_id?:    string | null;
  vercel_verification?: Record<string, unknown> | null;
  created_at?:          string;
  updated_at?:          string;
}

