/**
 * Supabase Database Type Definitions
 *
 * Strongly-typed schema for the Mister Chameleon Supabase database.
 * These types are consumed by the Supabase JS client via the generic
 * parameter in `createClient<Database>(...)`, providing end-to-end
 * type safety for all table reads and writes.
 *
 * ─── Schema overview ──────────────────────────────────────────────────────────
 *
 *   sessions        — one row per visitor session
 *   served_variants — the variant set resolved for each session
 *   events          — arbitrary named events tied to a session
 *
 * ─── Keeping types in sync ────────────────────────────────────────────────────
 *
 *   This file is the hand-authored source of truth until the Supabase CLI
 *   type generator is wired in. When the SQL schema changes, update the
 *   `Row`, `Insert`, and `Update` types below to match.
 *
 *   To switch to auto-generated types:
 *     npx supabase gen types typescript --project-id <id> > src/data/database.types.ts
 *   Then re-export from this file or replace it.
 *
 * ─── SQL migration reference ──────────────────────────────────────────────────
 *
 *   See supabase/migrations/ for the CREATE TABLE statements that define
 *   the backing schema.
 */

// ── sessions ──────────────────────────────────────────────────────────────────

export interface SessionRow {
  /** UUID primary key, generated by the database. */
  id: string;
  /** ISO-8601 timestamp set by the database on insert. */
  created_at: string;
  /** Resolved traffic source — linkedin | google | direct | unknown */
  source: string;
  /** Detected device class — mobile | desktop */
  device: string;
  /** First or returning visit — new | returning */
  visit_type: string;
  /** Pathname of the page that triggered session creation, e.g. "/" */
  pathname: string;
  /** Full Referer header value, null if absent */
  referrer: string | null;
  /** utm_source query parameter */
  utm_source: string | null;
  /** utm_medium query parameter */
  utm_medium: string | null;
  /** utm_campaign query parameter */
  utm_campaign: string | null;
}

export interface SessionInsert {
  /** Optional: omit to let the database generate a UUID. */
  id?: string;
  /** Optional: omit to let the database set to now(). */
  created_at?: string;
  source: string;
  device: string;
  visit_type: string;
  pathname: string;
  referrer?: string | null;
  utm_source?: string | null;
  utm_medium?: string | null;
  utm_campaign?: string | null;
}

