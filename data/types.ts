// ── ai_decision_logs ──────────────────────────────────────────────────────────

/**
 * JSONB shape stored in `ai_decision_logs.live_plan` and `shadow_plan`.
 * Matches the ExperiencePlan structure plus AI-specific metadata fields
 * (confidence, policy verdict, model info) for the shadow column.
 */
export interface AiPlanSnapshot {
  heroKey: string;
  proofKey: string;
  ctaKey: string;
  reason: string;
  /** AI confidence score (0-1), only present in shadow_plan */
  confidence?: number;
  /** Confidence policy verdict, only present in shadow_plan */
  policyVerdict?: string;
  /** Context richness score at decision time, only present in shadow_plan */
  contextRichness?: number;
  /** Model that produced this plan, only present in shadow_plan */
  modelId?: string;
  /** Inference latency in ms, only present in shadow_plan */
  latencyMs?: number;
  /** Policy gate results, only present in shadow_plan */
  gateResults?: Array<{ gate: string; passed: boolean; score?: number }>;
}

/** JSONB shape stored in `ai_decision_logs.context` */
export interface AiContextSnapshot {
  source: string;
  device: string;
  visitType: string;
  utmSource: string | null;
  utmMedium: string | null;
  utmCampaign: string | null;
  referrerDomain: string | null;
  pathname?: string;
}

export interface AiDecisionLogRow {
  /** UUID primary key, generated by the database */
  id: string;
  /** FK → sessions.id */
  session_id: string;
  /** ISO-8601 timestamp */
  created_at: string;
  /**
   * Tenant slug that originated the decision, e.g. "mister-chameleon".
   * Null for rows written before migration 20240101000007.
   */
  tenant_id: string | null;
  /** Page the decision was for, e.g. "homepage" */
  page_type: string;
  /** Name of the provider that produced the rendered plan, e.g. "rules" | "ai:claude" */
  live_provider: string;
  /** JSONB snapshot of the rendered ExperiencePlan */
  live_plan: AiPlanSnapshot;
  /** Name of the AI provider that ran, e.g. "claude" | "openai" */
  shadow_provider: string;
  /** JSONB snapshot of the AI ExperiencePlan with confidence metadata */
  shadow_plan: AiPlanSnapshot;
  /** true when heroKey + proofKey + ctaKey match across live and shadow plans */
  plans_match: boolean;
  /** JSONB snapshot of the VisitorContext at decision time */
  context: AiContextSnapshot;
}

export interface AiDecisionLogInsert {
  id?: string;
  session_id: string;
  created_at?: string;
  /**
   * Tenant slug that originated the decision.
   * Omit (or pass undefined/null) when the tenant is unknown.
   * Never pass API keys or credentials — those stay in process.env only.
   */
  tenant_id?: string | null;
  page_type: string;
  live_provider: string;
  live_plan: AiPlanSnapshot;
  shadow_provider: string;
  shadow_plan: AiPlanSnapshot;
  plans_match: boolean;
  context: AiContextSnapshot;
}

// ── experiments ───────────────────────────────────────────────────────────────

/**
 * One row per defined A/B experiment.
 * Managed via the Supabase dashboard or direct SQL inserts.
 */
export interface ExperimentRow {
  /** Stable text slug, e.g. "hero_problem_vs_brand_2025_q2" */
  id: string;
  /** Human-readable label for the dashboard */
  name: string;
  /** Which page slot is being tested: hero | proof | cta */
  slot: "hero" | "proof" | "cta";
  /**
   * Ordered array of variant keys.
   * Index 0 → bucket 0, index 1 → bucket 1, etc.
   * Must contain at least two entries.
   */
  variants: string[];
  /** Lifecycle state */
  status: "active" | "paused" | "ended";
  /** Proportion of sessions enrolled: 0 < f ≤ 1.0 */
  traffic_fraction: number;
  /** ISO-8601 creation timestamp */
  created_at: string;
  /** ISO-8601 timestamp set when status transitions to "ended", or null */
  ended_at: string | null;
}

export interface ExperimentInsert {
  /** Required stable slug */
  id: string;
  name: string;
  slot: "hero" | "proof" | "cta";
  variants: string[];
  /** Defaults to "active" in the database */
  status?: "active" | "paused" | "ended";
  /** Defaults to 1.0 in the database */
  traffic_fraction?: number;
  created_at?: string;
  ended_at?: string | null;
}

// ── experiment_assignments ─────────────────────────────────────────────────────

/**
 * One row per (session × experiment) pair.
 * Written on the first request a session is enrolled in an experiment;
 * subsequent requests reuse the deterministic bucket without another write.
 */
export interface ExperimentAssignmentRow {
  /** UUID primary key */
  id: string;
  /** FK → sessions.id */
  session_id: string;
  /** FK → experiments.id */
  experiment_id: string;
  /** 0-based bucket index into experiments.variants */
  bucket: number;
  /** Resolved variant key (denormalised for query convenience) */
  variant_key: string;
  /** ISO-8601 assignment timestamp */
  created_at: string;
}

export interface ExperimentAssignmentInsert {
  id?: string;
  session_id: string;
  experiment_id: string;
  bucket: number;
  variant_key: string;
  created_at?: string;
}

// ── form_submissions ──────────────────────────────────────────────────────────

/**
 * One row per submitted and validated form — written by the
 * /api/forms/[formKey] route when formDef.action.storeSubmissions is true.
 *
 * SQL:
 *   form_submissions (
 *     id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
 *     created_at  timestamptz NOT NULL DEFAULT now(),
 *     form_key    text        NOT NULL,
 *     values      jsonb       NOT NULL,
 *     session_id  uuid        NULL REFERENCES sessions(id) ON DELETE SET NULL
 *   )
 */
export interface FormSubmissionRow {
  /** UUID primary key, generated by the database. */
  id:          string;
  /** ISO-8601 timestamp set by the database on insert. */
  created_at:  string;
  /** Registered form key, e.g. "contact" | "application" */
  form_key:    string;
  /** Validated, trimmed submission values keyed by field key. */
  values:      Record<string, string>;
  /** FK → sessions.id — nullable; absent for submissions without a platform session. */
  session_id:  string | null;
}

export interface FormSubmissionInsert {
  /** Optional: omit to let the database generate a UUID. */
  id?:         string;
  /** Optional: omit to let the database set to now(). */
  created_at?: string;
  form_key:    string;
  values:      Record<string, string>;
  session_id?: string | null;
}

