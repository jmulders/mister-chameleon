// ── Brand / identity metadata ─────────────────────────────────────────────────

export interface TenantBrandMeta {
  /** Human-readable display name. */
  name: string;
  /** One-sentence positioning statement. */
  tagline?: string;
  /** Path to the tenant's logo, relative to /public. */
  logoPath?: string;
  /** Path to the favicon, relative to /public. */
  faviconPath?: string;
}

// ── Root TenantTheme ──────────────────────────────────────────────────────────

/**
 * Complete visual identity and brand configuration for a single tenant.
 *
 * Every field maps to one or more CSS custom properties that override the
 * design-system :root defaults. See tenantThemeToCSS() for the exact mapping.
 */
export interface TenantTheme {
  colors: {
    brand:      TenantBrandColors;
    text:       TenantTextColors;
    background: TenantBackgroundColors;
    border:     TenantBorderColors;
  };
  /** Corner radius personality. See RADIUS_PRESETS. */
  radius: RadiusPersonality;
  /** Brand identity metadata. */
  meta: TenantBrandMeta;
  /** Optional typography overrides. */
  typography?: ThemeTypography;
  /** Optional button component token overrides. */
  button?: ThemeButtonTokens;
  /** Optional motion / animation token overrides. */
  motion?: ThemeMotionTokens;
  /** Optional component-level style overrides. */
  componentStyles?: ThemeComponentStyles;
}

// ── CSS variable generator ────────────────────────────────────────────────────

/**
 * Converts a TenantTheme to a block of CSS custom property declarations.
 *
 * Returns the inner content of a :root { } rule — each line is indented
 * with two spaces and ends with a semicolon.
 */
export function tenantThemeToCSS(theme: TenantTheme): string {
  const { colors, radius, typography, button, motion, componentStyles: cs } = theme;
  const r = RADIUS_PRESETS[radius];

  // ── Derived defaults ────────────────────────────────────────────────────────

  // Section / card
  const heroBg             = cs?.heroBg              ?? neutral[950];
  const ctaBg              = cs?.ctaBg               ?? colors.brand.primary;
  const ctaBodyText        = cs?.ctaBodyText          ?? colors.brand.primarySubtle;
  const subtleBg           = cs?.subtleSectionBg     ?? colors.background.bgSubtle;
  const subtleBorder       = cs?.subtleSectionBorder  ?? colors.border.border;
  const cardBg             = cs?.cardBg              ?? "#ffffff";
  const cardBorder         = cs?.cardBorderColor     ?? colors.border.border;
  const cardRadius         = cs?.cardRadius          ?? r.card;
  const cardShadow         = cs?.cardShadow          ?? shadows.sm;
  const quoteColor         = cs?.quoteColor          ?? colors.brand.primary;

  // Hero expansion
  const heroGlowColor      = cs?.heroGlowColor       ?? colors.brand.primary;
  const heroGlowOpacity    = cs?.heroGlowOpacity     ?? "0.2";
  const heroTitleColor     = cs?.heroTitleColor      ?? colors.text.textInverse;
  const heroSubtitleColor  = cs?.heroSubtitleColor   ?? colors.text.textSubtle;

  // Proof
  const proofBg            = cs?.proofBg             ?? colors.background.bg;
  const proofBorder        = cs?.proofBorder         ?? "transparent";
  const proofCardBg        = cs?.proofCardBg         ?? cardBg;
  const proofCardBorder    = cs?.proofCardBorder     ?? cardBorder;
  const proofCardRadius    = cs?.proofCardRadius     ?? cardRadius;
  const proofCardShadow    = cs?.proofCardShadow     ?? cardShadow;
  const proofQuoteColor    = cs?.proofQuoteColor     ?? quoteColor;

  // Feature-grid
  const fgBg               = cs?.featureGridBg          ?? subtleBg;
  const fgBorder           = cs?.featureGridBorder      ?? subtleBorder;
  const fgCardBg           = cs?.featureGridCardBg      ?? cardBg;
  const fgCardBorder       = cs?.featureGridCardBorder  ?? cardBorder;
  const fgCardRadius       = cs?.featureGridCardRadius  ?? cardRadius;
  const fgCardShadow       = cs?.featureGridCardShadow  ?? cardShadow;
  const fgIconBg           = cs?.featureGridIconBg      ?? subtleBg;

  // Typography
  const headingFont        = typography?.headingFont      ?? fontFamily.sans;
  const headingWeight      = typography?.headingWeight    ?? "700";
  const subheadingWeight   = typography?.subheadingWeight ?? "600";

  // Button
  const btnBg              = button?.bg         ?? colors.brand.primary;
  const btnText            = button?.text        ?? colors.brand.primaryText;
  const btnHoverBg         = button?.hoverBg     ?? colors.brand.primaryHover;
  const btnActiveBg        = button?.activeBg    ?? colors.brand.primaryActive;
  const btnRing            = button?.ring        ?? colors.brand.ring;
  const btnRadius          = button?.radius      ?? r.interactive;
  const btnShadow          = button?.shadow      ?? shadows.sm;
  const btnFontWeight      = button?.fontWeight  ?? "600";

  // Motion
  const easeBase           = "cubic-bezier(0.4, 0, 0.2, 1)";
  const transitionFast     = motion?.transitionFast  ?? `100ms ${easeBase}`;
  const transitionBase     = motion?.transitionBase  ?? `150ms ${easeBase}`;
  const transitionSlow     = motion?.transitionSlow  ?? `300ms ${easeBase}`;
  const easingDefault      = motion?.easingDefault   ?? easeBase;
  const easingSpring       = motion?.easingSpring    ?? "cubic-bezier(0.34, 1.56, 0.64, 1)";

  const vars: [string, string][] = [
    // ── Brand / interactive ───────────────────────────────────────────────────
    ["--primary",           colors.brand.primary],
    ["--primary-hover",     colors.brand.primaryHover],
    ["--primary-active",    colors.brand.primaryActive],
    ["--primary-subtle",    colors.brand.primarySubtle],
    ["--primary-text",      colors.brand.primaryText],
    ["--ring",              colors.brand.ring],
    ["--text-brand",        colors.brand.textBrand],

    // ── Text ─────────────────────────────────────────────────────────────────
    ["--text",              colors.text.text],
    ["--text-muted",        colors.text.textMuted],
    ["--text-subtle",       colors.text.textSubtle],
    ["--text-inverse",      colors.text.textInverse],

    // ── Backgrounds ───────────────────────────────────────────────────────────
    ["--bg",                colors.background.bg],
    ["--bg-subtle",         colors.background.bgSubtle],
    ["--bg-inverse",        colors.background.bgInverse],

    // ── Borders ───────────────────────────────────────────────────────────────
    ["--border",            colors.border.border],
    ["--border-strong",     colors.border.borderStrong],

    // ── Component radii ───────────────────────────────────────────────────────
    ["--radius-interactive", r.interactive],
    ["--radius-card",        r.card],
    ["--radius-popover",     r.popover],

    // ── Motion ────────────────────────────────────────────────────────────────
    ["--transition-fast",  transitionFast],
    ["--transition-base",  transitionBase],
    ["--transition-slow",  transitionSlow],
    ["--ease-default",     easingDefault],
    ["--ease-spring",      easingSpring],

    // ── Button ────────────────────────────────────────────────────────────────
    ["--btn-bg",           btnBg],
    ["--btn-text",         btnText],
    ["--btn-hover-bg",     btnHoverBg],
    ["--btn-active-bg",    btnActiveBg],
    ["--btn-ring",         btnRing],
    ["--btn-radius",       btnRadius],
    ["--btn-shadow",       btnShadow],
    ["--btn-font-weight",  btnFontWeight],

    // ── Section surface tokens ────────────────────────────────────────────────
    ["--section-hero-bg",        heroBg],
    ["--section-cta-bg",         ctaBg],
    ["--section-cta-body",       ctaBodyText],
    ["--section-subtle-bg",      subtleBg],
    ["--section-subtle-border",  subtleBorder],

    // ── Card tokens ───────────────────────────────────────────────────────────
    ["--card-bg",          cardBg],
    ["--card-border",      cardBorder],
    ["--card-radius",      cardRadius],
    ["--card-shadow",      cardShadow],
    ["--card-quote",       quoteColor],

    // ── Hero component tokens ─────────────────────────────────────────────────
    ["--hero-bg",              heroBg],
    ["--hero-glow-color",      heroGlowColor],
    ["--hero-glow-opacity",    heroGlowOpacity],
    ["--hero-title-color",     heroTitleColor],
    ["--hero-subtitle-color",  heroSubtitleColor],

    // ── Proof / testimonial tokens ────────────────────────────────────────────
    ["--proof-bg",           proofBg],
    ["--proof-border",       proofBorder],
    ["--proof-card-bg",      proofCardBg],
    ["--proof-card-border",  proofCardBorder],
    ["--proof-card-radius",  proofCardRadius],
    ["--proof-card-shadow",  proofCardShadow],
    ["--proof-quote-color",  proofQuoteColor],

    // ── Feature-grid tokens ───────────────────────────────────────────────────
    ["--feature-grid-bg",           fgBg],
    ["--feature-grid-border",       fgBorder],
    ["--feature-grid-card-bg",      fgCardBg],
    ["--feature-grid-card-border",  fgCardBorder],
    ["--feature-grid-card-radius",  fgCardRadius],
    ["--feature-grid-card-shadow",  fgCardShadow],
    ["--feature-grid-icon-bg",      fgIconBg],

    // ── Typography component tokens ───────────────────────────────────────────
    ["--font-heading",           headingFont],
    ["--font-heading-weight",    headingWeight],
    ["--font-subheading-weight", subheadingWeight],
  ];

  return vars.map(([key, val]) => `  ${key}: ${val};`).join("\n") + "\n";
}

