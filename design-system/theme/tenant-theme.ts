  /** Feature-grid section background. */
  featureGridBg?: string;
  /** Feature-grid section border. */
  featureGridBorder?: string;
  /** Feature-grid card background. */
  featureGridCardBg?: string;
  /** Feature-grid card border. */
  featureGridCardBorder?: string;
  /** Feature-grid card radius. */
  featureGridCardRadius?: string;
  /** Feature-grid card shadow. */
  featureGridCardShadow?: string;
  /** Feature-grid icon container background (icons-left variant). */
  featureGridIconBg?: string;
