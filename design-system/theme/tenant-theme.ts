// ── Radius personality ────────────────────────────────────────────────────────
//
// Rather than exposing every radius token, tenants pick a personality.
// The RADIUS_PRESETS map translates each personality into component-level
// CSS var values injected alongside the colour vars.

export type RadiusPersonality = "sharp" | "balanced" | "soft";

export interface TenantRadiusValues {
  interactive: string; // --radius-interactive
  card: string;        // --radius-card
  popover: string;     // --radius-popover
}

export const RADIUS_PRESETS: Record<RadiusPersonality, TenantRadiusValues> = {
  sharp: {
    interactive: radii.xs,   //  2px
    card:        radii.sm,   //  4px
    popover:     radii.xs,   //  2px
  },
  balanced: {
    interactive: radii.md,   //  8px
    card:        radii.xl,   // 16px
    popover:     radii.lg,   // 12px
  },
  soft: {
    interactive: radii.lg,       // 12px
    card:        radii["2xl"],   // 24px
    popover:     radii.xl,       // 16px
  },
} as const satisfies Record<RadiusPersonality, Record<string, (typeof radii)[RadiusKey]>>;

