  /** Border on subtle sections. */
  subtleSectionBorder?: string;

  // ── Card tokens ─────────────────────────────────────────────────────────────
  /** Card/panel background. Defaults to #ffffff. */
  cardBg?: string;
  /** Card border colour. */
  cardBorderColor?: string;
  /** Card border-radius. Defaults to --radius-card. */
  cardRadius?: string;
  /** Card box-shadow. Defaults to shadow-sm. */
  cardShadow?: string;
