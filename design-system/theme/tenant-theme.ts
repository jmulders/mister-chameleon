/**
 * Tenant Theme — Types, Presets, and CSS Variable Generator
 *
 * This file is the bridge between the design system and tenant configuration.
 *
 * ─── What lives here ─────────────────────────────────────────────────────────
 *
 *   TenantTheme          The shape every tenant theme must satisfy.
 *   RADIUS_PRESETS       Three personality presets — sharp, balanced, soft.
 *   tenantThemeToCSS()   Converts a TenantTheme to inline CSS custom property
 *                        declarations that override the :root defaults from
 *                        theme.css without touching any component code.
 *
 * ─── How it plugs into the design system ────────────────────────────────────
 *
 *   theme.css defines the base :root semantic vars (--primary, --bg, --text, …)
 *   that all components consume. The CSS generated by tenantThemeToCSS() uses
 *   the exact same variable names, so injecting it as an inline <style> block
 *   in the root layout overrides those defaults at the :root level — zero
 *   component changes needed.
 *
 *   The full palette (brand.50–950, neutral.0–950) remains unchanged in the
 *   @theme layer — TenantTheme only overrides the semantic alias variables,
 *   not the raw palette.
 *
 * ─── What TenantTheme does NOT control ──────────────────────────────────────
 *
 *   • The raw palette tokens (--color-brand-*, --color-neutral-*) — these are
 *     part of the Tailwind @theme layer and are compile-time constants.
 *   • Typography scale, spacing scale — shared across all tenants.
 *   • Dark mode overrides — tenants can add a `dark` sub-theme later if needed.
 *   • Component variants, layout structure — shared via the design system.
 *
 * ─── Adding a second tenant ──────────────────────────────────────────────────
 *
 *   Create tenant/<slug>-theme.ts satisfying TenantTheme, set the fields, and
 *   reference it from the tenant config. No other files change.
 */

