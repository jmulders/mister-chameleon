/**
 * Tenant Theme — Types, Presets, and CSS Variable Generator
 *
 * This file is the bridge between the design system and tenant configuration.
 *
 * ─── What lives here ─────────────────────────────────────────────────────────
 *
 *   TenantTheme          The shape every tenant theme must satisfy.
 *   RADIUS_PRESETS       Three personality presets — sharp, balanced, soft.
 *   tenantThemeToCSS()   Converts a TenantTheme to inline CSS custom property
 *                        declarations that override the :root defaults from
 *                        theme.css without touching any component code.
 *
 * ─── How it plugs into the design system ────────────────────────────────────
 *
 *   theme.css defines the base :root semantic vars (--primary, --bg, --text, …)
 *   that all components consume. The CSS generated by tenantThemeToCSS() uses
 *   the exact same variable names, so injecting it as an inline <style> block
 *   in the root layout overrides those defaults at the :root level — zero
 *   component changes needed.
 *
 *   The full palette (brand.50–950, neutral.0–950) remains unchanged in the
 *   @theme layer — TenantTheme only overrides the semantic alias variables,
 *   not the raw palette.
 *
 * ─── What TenantTheme does NOT control ──────────────────────────────────────
 *
 *   • The raw palette tokens (--color-brand-*, --color-neutral-*) — these are
 *     part of the Tailwind @theme layer and are compile-time constants.
 *   • Typography scale, spacing scale — shared across all tenants.
 *   • Dark mode overrides — tenants can add a `dark` sub-theme later if needed.
 *   • Component variants, layout structure — shared via the design system.
 *
 * ─── Adding a second tenant ──────────────────────────────────────────────────
 *
 *   Create tenant/<slug>-theme.ts satisfying TenantTheme, set the fields, and
 *   reference it from the tenant config. No other files change.
 */

import { brand, neutral } from "../tokens/colors";
import { radii } from "../tokens/radii";
import type { RadiusKey } from "../tokens/radii";
import { fontFamily } from "../tokens/typography";
import { shadows } from "../tokens/shadow";

// ── Brand color surface ───────────────────────────────────────────────────────

export interface TenantBrandColors {
  /** --primary: main interactive colour — button bg, active link, badge fill */
  primary: string;
  /** --primary-hover: :hover / :focus-visible state of primary elements */
  primaryHover: string;
  /** --primary-active: :active / pressed state of primary elements */
  primaryActive: string;
  /** --primary-subtle: lightly tinted background behind primary elements */
  primarySubtle: string;
  /** --primary-text: text on a primary-coloured background (usually white) */
  primaryText: string;
  /** --ring: colour of the keyboard focus ring */
  ring: string;
  /** --text-brand: brand-coloured inline text (links, callouts) */
  textBrand: string;
}

// ── Text color surface ────────────────────────────────────────────────────────

export interface TenantTextColors {
  /** --text: default body text colour */
  text: string;
  /** --text-muted: secondary / descriptive text */
  textMuted: string;
  /** --text-subtle: placeholder text, disabled states, timestamps */
  textSubtle: string;
  /** --text-inverse: text on dark / coloured backgrounds */
  textInverse: string;
}

// ── Background / surface color surface ───────────────────────────────────────

export interface TenantBackgroundColors {
  /** --bg: default page background */
  bg: string;
  /** --bg-subtle: recessed areas — sidebars, alternate rows, code blocks */
  bgSubtle: string;
  /** --bg-inverse: dark background for inverse sections */
  bgInverse: string;
}

// ── Border color surface ──────────────────────────────────────────────────────

export interface TenantBorderColors {
  /** --border: default dividers and input borders */
  border: string;
  /** --border-strong: stronger dividers, active input borders */
  borderStrong: string;
}

// ── Radius personality ────────────────────────────────────────────────────────
//
// Rather than exposing every radius token, tenants pick a personality.
// The RADIUS_PRESETS map translates each personality into component-level
// CSS var values injected alongside the colour vars.

export type RadiusPersonality = "sharp" | "balanced" | "soft";

export interface TenantRadiusValues {
  interactive: string; // --radius-interactive
  card: string;        // --radius-card
  popover: string;     // --radius-popover
}

export const RADIUS_PRESETS: Record<RadiusPersonality, TenantRadiusValues> = {
  sharp: {
    interactive: radii.xs,   //  2px
    card:        radii.sm,   //  4px
    popover:     radii.xs,   //  2px
  },
  balanced: {
    interactive: radii.md,   //  8px
    card:        radii.xl,   // 16px
    popover:     radii.lg,   // 12px
  },
  soft: {
    interactive: radii.lg,       // 12px
    card:        radii["2xl"],   // 24px
    popover:     radii.xl,       // 16px
  },
} as const satisfies Record<RadiusPersonality, Record<string, (typeof radii)[RadiusKey]>>;

// ── Typography overrides ──────────────────────────────────────────────────────

export interface ThemeTypography {
  /** Heading font-family stack. Overrides --font-heading. */
  headingFont?: string;
  /** Heading font-weight. Overrides --font-heading-weight. Defaults to "700". */
  headingWeight?: string;
  /** Sub-heading font-weight. Overrides --font-subheading-weight. Defaults to "600". */
  subheadingWeight?: string;
}

// ── Button component tokens ───────────────────────────────────────────────────
//
// A dedicated token group for button surfaces.  Using these instead of
// --primary / --primary-hover directly means button style can diverge from
// the global brand accent colour when needed.
//
// All fields are optional — absent values derive from the brand color surface
// in tenantThemeToCSS().

export interface ThemeButtonTokens {
  /** --btn-bg: default button background. Defaults to --primary. */
  bg?: string;
  /** --btn-text: text on the button background. Defaults to --primary-text. */
  text?: string;
  /** --btn-hover-bg: :hover / :focus-visible background. */
  hoverBg?: string;
  /** --btn-active-bg: :active / pressed background. */
  activeBg?: string;
  /** --btn-ring: focus ring colour. Defaults to --ring. */
  ring?: string;
  /** --btn-radius: border-radius. Defaults to --radius-interactive. */
  radius?: string;
  /** --btn-shadow: optional lift shadow. Defaults to shadow-sm. */
  shadow?: string;
  /** --btn-font-weight: label font-weight. Defaults to "600". */
  fontWeight?: string;
}

// ── Motion tokens ─────────────────────────────────────────────────────────────
//
// Transition timing and easing for the tenant's interaction feel.
// Optional — platform defaults (150ms ease-in-out) apply when absent.

export interface ThemeMotionTokens {
  /** --transition-fast: micro-interaction speed. Default "100ms ease-in-out". */
  transitionFast?: string;
  /** --transition-base: default speed. Default "150ms ease-in-out". */
  transitionBase?: string;
  /** --transition-slow: panel/overlay speed. Default "300ms ease-in-out". */
  transitionSlow?: string;
  /** --ease-default: standard easing. */
  easingDefault?: string;
  /** --ease-spring: bouncy easing for expressive interactions. */
  easingSpring?: string;
}

