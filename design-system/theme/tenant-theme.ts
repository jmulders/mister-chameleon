  // ── Hero expansion ──────────────────────────────────────────────────────────
  /** Glow decoration colour. Defaults to --primary. */
  heroGlowColor?: string;
  /** Opacity of the hero glow (0–1 string). Defaults to "0.2". */
  heroGlowOpacity?: string;
  /** Hero headline text colour. Defaults to --text-inverse. */
  heroTitleColor?: string;
  /** Hero subheadline colour. Defaults to --text-subtle. */
  heroSubtitleColor?: string;

  // ── Proof / testimonial tokens ──────────────────────────────────────────────
  /** Proof section background. */
  proofBg?: string;
  /** Proof section border. Defaults to "transparent". */
  proofBorder?: string;
  /** Proof card background. Defaults to --card-bg. */
  proofCardBg?: string;
