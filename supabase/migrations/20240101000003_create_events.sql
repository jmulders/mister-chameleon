COMMENT ON TABLE  public.events            IS 'Named events tied to a visitor session — page views, CTA clicks, form submits, etc.';
COMMENT ON COLUMN public.events.id         IS 'UUID primary key, generated by Postgres.';
COMMENT ON COLUMN public.events.session_id IS 'FK to sessions.id; cascades on delete.';
COMMENT ON COLUMN public.events.created_at IS 'Event timestamp, set by Postgres.';
COMMENT ON COLUMN public.events.event_type IS 'Snake-case event name, e.g. page_view or cta_click.';
COMMENT ON COLUMN public.events.payload    IS 'Open JSONB metadata for the event; defaults to {}.';
